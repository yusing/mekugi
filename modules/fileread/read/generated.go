package read

import (
	"regexp"
	"strings"
)

const generatedReminder = "Generated file: edit the source and regenerate."

// Match declarations, not arbitrary mentions of generation in comment prose.
var generatedMarker = regexp.MustCompile(`(?i)^(?:@generated\b|<auto-generated\b|code generated\b.*\bdo not edit\b|(?:this file (?:is|was) )?generated (?:by|from|with)\b|(?:this file (?:is|was) )?(?:(?:automatically generated|auto-generated|autogenerated)(?: file)?|generated file)(?:\s*$|[.:;!]|\s+(?:by|from|with)\b))`)

// generatedHeader recognizes common comment delimiters without parsing or retaining
// the source. Only blank rows, a shebang, and leading comments precede a marker.
type generatedHeader struct {
	end   string
	done  bool
	found bool
}

func (h *generatedHeader) accept(row string, first bool) {
	if h.done {
		return
	}
	if first {
		row = strings.TrimPrefix(row, "\ufeff")
	}
	row = strings.TrimSpace(row)
	if first && strings.HasPrefix(row, "#!") {
		return
	}
	for row != "" {
		if h.end != "" {
			body, rest, closed := strings.Cut(row, h.end)
			h.check(strings.TrimSpace(strings.TrimLeft(body, "*")))
			if !closed || h.done {
				return
			}
			h.end = ""
			row = strings.TrimSpace(rest)
			continue
		}
		for _, delimiter := range []struct{ start, end string }{
			{"/*", "*/"}, {"<!--", "-->"}, {"(*", "*)"},
		} {
			if strings.HasPrefix(row, delimiter.start) {
				h.end = delimiter.end
				row = strings.TrimSpace(strings.TrimPrefix(row, delimiter.start))
				break
			}
		}
		if h.end != "" {
			continue
		}
		for _, prefix := range []string{"//", "#", "--", ";", "%"} {
			if strings.HasPrefix(row, prefix) {
				h.check(strings.TrimSpace(strings.TrimPrefix(row, prefix)))
				return
			}
		}
		h.done = true
		return
	}
}

func (h *generatedHeader) check(comment string) {
	if generatedMarker.MatchString(comment) {
		h.found, h.done = true, true
	}
}
