func TestNativeSymbolRealRustSelectedConfiguration(t *testing.T) {
	if os.Getenv("MEKUGI_TEST_REAL_RUST_ANALYZER") != "1" {
		t.Skip("set MEKUGI_TEST_REAL_RUST_ANALYZER=1 for installed Rust acceptance")
	}
	root := t.TempDir()
	// The inactive path dependency contains an executable sentinel, but is not in
	// the selected platform graph. The disabled module has unavailable generation.
	for name, source := range map[string]string{
		"Cargo.toml":           "[workspace]\nmembers=[\"main\"]\nexclude=[\"inactive\"]\nresolver=\"2\"\n",
		"main/Cargo.toml":      "[package]\nname=\"symbol_main\"\nversion=\"0.1.0\"\nedition=\"2021\"\n[features]\ndefault=[\"enabled\"]\nenabled=[]\ndisabled=[]\n[target.'cfg(windows)'.dependencies]\ninactive={path=\"../inactive\"}\n",
		"main/src/lib.rs":      "#[cfg(feature=\"disabled\")] mod inactive;\n#[cfg(feature=\"enabled\")] pub fn active() {}\npub fn caller() { active(); }\n",
		"main/src/inactive.rs": "include!(concat!(env!(\"OUT_DIR\"), \"/missing.rs\"));\n",
		"inactive/Cargo.toml":  "[package]\nname=\"inactive\"\nversion=\"0.1.0\"\nedition=\"2021\"\n",
		"inactive/src/lib.rs":  "pub fn unused() {}\n",
		"inactive/build.rs":    "fn main(){ std::fs::write(" + strconv.Quote(filepath.Join(root, "SCRIPT_RAN")) + ", \"bad\").unwrap(); }\n",
		".cargo/config.toml":   "[build]\ntarget=\"x86_64-unknown-linux-gnu\"\n",
	} {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
	}
	lock := exec.Command("cargo", "generate-lockfile", "--offline")
	lock.Dir = root
	if output, err := lock.CombinedOutput(); err != nil {
		t.Fatalf("fixture lock: %v %s", err, output)
	}
	out := executeQuery(t, "--workspace", root, "refs", "main/src/lib.rs", "active")
	if out.ExitCode != 0 || !strings.Contains(out.Stdout, "pub fn caller()") {
		t.Fatalf("selected default configuration: %+v", out)
	}
	if _, err := os.Stat(filepath.Join(root, "SCRIPT_RAN")); !os.IsNotExist(err) {
		t.Fatal("inactive dependency build script ran")
	}
}
