func TestNativeSymbolRustKnownIncompleteSkipsCoverageWork(t *testing.T) {
	root := rustWorkspace(t)
	target := filepath.Join(root, "core/src/lib.rs")
	log := installSymbolResolvers(t, map[string]symbolResolverFixture{"rust-analyzer": {
		Definitions: []symbolFixtureLocation{nativeSymbolFixtureLocation(target, 1, 7, 13)},
		References:  []symbolFixtureLocation{nativeSymbolFixtureLocation(target, 1, 7, 13)},
		RustHealth:  "ok",
	}})
	installRustPrerequisites(t, root)
	cargo := filepath.Join(filepath.SplitList(os.Getenv("PATH"))[0], "cargo")
	script, err := os.ReadFile(cargo)
	if err != nil {
		t.Fatal(err)
	}
	script = bytes.ReplaceAll(script, []byte(`"kind":["lib"]`), []byte(`"kind":["lib","custom-build"]`))
	if err := os.WriteFile(cargo, script, 0700); err != nil {
		t.Fatal(err)
	}
	out := executeQuery(t, "--workspace", root, "def", target, "r#type", "refs", target, "r#type")
	if out.ExitCode != 1 || !strings.Contains(out.Stdout, "pub fn r#type()") || !strings.Contains(out.Stderr, "disabled build scripts or procedural macros") {
		t.Fatalf("known incomplete: %+v", out)
	}
	initialized := false
	for _, event := range readSymbolLog(t, log) {
		switch event.Message.Method {
		case "initialize":
			initialized = true
			priming, _ := event.Message.Params.InitializationOptions["cachePriming"].(map[string]any)
			if priming["enable"] != false {
				t.Fatal("one-shot query primes unrelated workspace caches")
			}
		case "textDocument/diagnostic", "textDocument/hover":
			t.Fatalf("known incomplete query did unnecessary coverage work: %s", event.Message.Method)
		}
	}
	if !initialized {
		t.Fatal("resolver did not initialize")
	}
}

