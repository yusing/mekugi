func TestNativeSymbolRealRustCoverage(t *testing.T) {
	if os.Getenv("MEKUGI_TEST_REAL_RUST_ANALYZER") != "1" {
		t.Skip("set MEKUGI_TEST_REAL_RUST_ANALYZER=1 for installed Rust acceptance")
	}
	for _, kind := range []string{"inactive", "suppressed_inactive", "unlinked", "generated", "build_script", "safe_config", "unsafe_config", "no_lock", "nested_config", "sibling_generated", "sibling_suppressed_generated", "active_with_inactive", "symlink_generated"} {
		t.Run(kind, func(t *testing.T) {
			root := rustWorkspace(t)
			path := "core/src/lib.rs"
			name := "r#type"
			write := func(name, source string) {
				t.Helper()
				if err := os.WriteFile(filepath.Join(root, name), []byte(source), 0600); err != nil {
					t.Fatal(err)
				}
			}
			switch kind {
			case "inactive", "suppressed_inactive":
				source := "#[cfg(feature=\"absent\")]\npub fn hidden() {}\n"
				if kind == "suppressed_inactive" {
					source = "#[allow(rust_analyzer::inactive_code)]\n" + source
				}
				write(path, source)
				name = "hidden"
			case "unlinked":
				path = "core/src/orphan.rs"
				write(path, "pub fn orphan() {}\n")
				name = "orphan"
			case "symlink_generated":
				if err := os.MkdirAll(filepath.Join(root, "shared"), 0700); err != nil {
					t.Fatal(err)
				}
				write("shared/nested.rs", "include!(concat!(env!(\"OUT_DIR\"), \"/generated.rs\"));\n")
				if err := os.Remove(filepath.Join(root, "core/src/nested.rs")); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(filepath.Join(root, "shared/nested.rs"), filepath.Join(root, "core/src/nested.rs")); err != nil {
					t.Fatal(err)
				}
			case "active_with_inactive":
				write(path, "#[cfg(any())] pub fn hidden() {}\npub fn r#type() -> i32 { 1 }\n")
			case "sibling_generated", "sibling_suppressed_generated":
				write(path, "mod nested;\npub fn r#type() -> i32 { 1 }\n")
				prefix := ""
				if kind == "sibling_suppressed_generated" {
					prefix = "#![allow(rust_analyzer::macro_error)]\n"
				}
				write("core/src/nested.rs", prefix+"include!(concat!(env!(\"OUT_DIR\"), \"/generated.rs\"));\n")
			case "nested_config":
				write("core/src/rust-analyzer.toml", "[diagnostics]\nenable=false\n")
			case "generated":
				write(path, "include!(concat!(env!(\"OUT_DIR\"), \"/generated.rs\"));\npub fn r#type() -> i32 { 1 }\n")
			case "build_script":
				write("core/build.rs", "fn main() { std::fs::write(\""+filepath.ToSlash(filepath.Join(root, "SCRIPT_RAN"))+"\",\"bad\").unwrap(); }\n")
			case "safe_config":
				write("rust-analyzer.toml", "[cargo.buildScripts]\nenable=false\n[completion]\nautoimport.enable=false\n")
			case "unsafe_config":
				write("rust-analyzer.toml", "[cargo.buildScripts]\nenable=true\n")
			case "no_lock":
				if err := os.Remove(filepath.Join(root, "Cargo.lock")); err != nil {
					t.Fatal(err)
				}
			}
			args := []string{"--workspace", root, "refs", path}

			args = append(args, name)
			out := executeQuery(t, args...)
			wantSuccess := kind == "safe_config" || kind == "active_with_inactive"
			if (out.ExitCode == 0) != wantSuccess {
				t.Fatalf("%s: %+v", kind, out)
			}
			if _, err := os.Stat(filepath.Join(root, "SCRIPT_RAN")); !os.IsNotExist(err) {
				t.Fatal("project build script executed")
			}
			if kind == "no_lock" {
				if _, err := os.Stat(filepath.Join(root, "Cargo.lock")); !os.IsNotExist(err) {
					t.Fatal("query wrote source-tree Cargo.lock")
				}
			}
		})
	}
}

