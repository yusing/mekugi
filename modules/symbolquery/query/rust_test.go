func rustWorkspace(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"Cargo.toml":         "[workspace]\nmembers = [\"core\",\"caller\"]\nresolver = \"2\"\n",
		"core/Cargo.toml":    "[package]\nname=\"symbol_core\"\nversion=\"0.1.0\"\nedition=\"2021\"\n",
		"caller/Cargo.toml":  "[package]\nname=\"symbol_caller\"\nversion=\"0.1.0\"\nedition=\"2021\"\n[dependencies]\nsymbol_core={path=\"../core\"}\n",
		"core/src/lib.rs":    "pub mod nested;\npub fn r#type() -> i32 { 1 }\npub struct Thing;\npub trait Value { fn value(&self) -> i32; }\nimpl Value for Thing { fn value(&self) -> i32 { r#type() } }\n",
		"core/src/nested.rs": "pub fn read() -> i32 { super::r#type() }\n",
		"caller/src/lib.rs":  "use symbol_core::{r#type, Thing, Value};\npub fn read() -> i32 { let _ = \"😀\"; r#type() + Thing.value() }\n",
		"Cargo.lock":         "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"symbol_core\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"symbol_caller\"\nversion = \"0.1.0\"\ndependencies = [\n \"symbol_core\",\n]\n",
	}
	for name, source := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func installRustPrerequisites(t *testing.T, root string) {
	t.Helper()
	dir := t.TempDir()
	sysroot := filepath.Join(dir, "sysroot")
	if err := os.MkdirAll(filepath.Join(sysroot, "lib/rustlib/src/rust/library/core/src"), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(sysroot, "lib/rustlib/src/rust/library/core/src/lib.rs"), nil, 0600); err != nil {
		t.Fatal(err)
	}
	quote := func(s string) string { return "'" + strings.ReplaceAll(s, "'", "'\\''") + "'" }
	metadata := `{"workspace_members":["core"],"resolve":{"nodes":[{"id":"core","deps":[]}]},"workspace_root":` + quotePath(root) + `,"packages":[{"id":"core","manifest_path":` + quotePath(filepath.Join(root, "core/Cargo.toml")) + `,"targets":[{"kind":["lib"]}]}]}`
	for name, body := range map[string]string{
		"rustc": "if [ \"$1\" = -vV ]; then echo 'host: x86_64-unknown-linux-gnu'; else printf '%s\\n' " + quote(sysroot) + "; fi",
		"cargo": "if [ \"$1\" = --version ]; then echo 'cargo 1.99.0'; elif [ \"$1\" = -Z ]; then echo '{}'; elif [ \"$1\" = locate-project ]; then printf '%s\\n' " + quote(filepath.Join(root, "Cargo.toml")) + "; else printf '%s' " + quote(metadata) + "; fi",
	} {
		script := "#!/bin/sh\n[ \"$RUSTUP_AUTO_INSTALL\" = 0 ] && [ \"$CARGO_NET_OFFLINE\" = true ] || exit 12\n" + body + "\n"
		if err := os.WriteFile(filepath.Join(dir, name), []byte(script), 0700); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
}

