package sessionapi

import (
	"encoding/json/jsontext"
	"fmt"
	"maps"
	"path"
	"reflect"
	"slices"
	"strconv"
	"strings"
	"time"
)

// TypeScript derives client wire types from the actual Go DTOs and method
// admission catalog. It is consumed by the contributor schema command.
func TypeScript() ([]byte, error) {
	g := typescriptTypes{names: make(map[reflect.Type]string), used: make(map[string]bool)}
	roots := []reflect.Type{
		reflect.TypeFor[PageCursor](), reflect.TypeFor[PageResult](), reflect.TypeFor[ContentReference](), reflect.TypeFor[ContentResult](),
		reflect.TypeFor[RPCMessage](), reflect.TypeFor[RPCInitialize](), reflect.TypeFor[RPCParams](), reflect.TypeFor[RPCEvent](), reflect.TypeFor[RPCClosed](), reflect.TypeFor[RPCSubscribed](),
		reflect.TypeFor[Start](), reflect.TypeFor[StartOptions](), reflect.TypeFor[InputRequest](), reflect.TypeFor[Answer](), reflect.TypeFor[NativeStart](), reflect.TypeFor[NativeMutation](), reflect.TypeFor[RemoteMutation](), reflect.TypeFor[NativeEvent](), reflect.TypeFor[NativeResult](), reflect.TypeFor[NativeExit](), reflect.TypeFor[listed](), reflect.TypeFor[message](),
	}
	for _, t := range roots {
		g.name(t)
	}
	var out strings.Builder
	out.WriteString("// Code generated by sessionapi-schema. DO NOT EDIT.\n// Native-only fields remain subject to server authority checks.\n\n")
	fmt.Fprintf(&out, "export const protocolVersion = %q as const;\nexport const subprotocol = %q as const;\n", ProtocolVersion, RPCSubprotocol)
	methods := slices.Sorted(maps.Keys(rpcMethods))
	for i := range methods {
		methods[i] = strconv.Quote(methods[i])
	}
	fmt.Fprintf(&out, "export type RPCMethod = \"initialize\" | %s;\n\n", strings.Join(methods, " | "))
	for len(g.queue) > 0 {
		t := g.queue[0]
		g.queue = g.queue[1:]
		value, err := g.value(t, true)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&out, "export type %s = %s;\n\n", g.names[t], value)
	}
	return []byte(strings.TrimSuffix(out.String(), "\n")), nil
}

type typescriptTypes struct {
	names map[reflect.Type]string
	used  map[string]bool
	queue []reflect.Type
}

func (g *typescriptTypes) name(t reflect.Type) string {
	if name := g.names[t]; name != "" {
		return name
	}
	name := t.Name()
	if name == "" {
		name = "Value"
	}
	if g.used[name] {
		name = (strings.ToUpper(path.Base(t.PkgPath())[:1]) + path.Base(t.PkgPath())[1:]) + "_" + name
	}
	base := name
	for i := 2; g.used[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	g.used[name] = true
	g.names[t] = name
	g.queue = append(g.queue, t)
	return name
}
func (g *typescriptTypes) value(t reflect.Type, definition bool) (string, error) {
	if t == reflect.TypeFor[jsontext.Value]() {
		return "unknown", nil
	}
	if t == reflect.TypeFor[time.Time]() {
		return "string", nil
	}
	if t.Kind() == reflect.Pointer {
		v, err := g.value(t.Elem(), false)
		return "(" + v + " | null)", err
	}
	if !definition && t.Name() != "" && t.Kind() == reflect.Struct {
		return g.name(t), nil
	}
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 && t.Kind() == reflect.Slice {
			return "string", nil
		}
		v, err := g.value(t.Elem(), false)
		return "Array<" + v + ">", err
	case reflect.Map:
		if k := t.Key().Kind(); k != reflect.String && !(k >= reflect.Int && k <= reflect.Uint64) {
			return "", fmt.Errorf("unsupported wire map %s", t)
		}
		v, err := g.value(t.Elem(), false)
		return "Record<string, " + v + ">", err
	case reflect.Struct:
		var fields []string
		var names []string
		var embedded []string
		for f := range t.Fields() {
			f := f
			tag := strings.Split(f.Tag.Get("json"), ",")
			name := tag[0]
			if f.PkgPath != "" || name == "-" {
				continue
			}
			v, err := g.value(f.Type, false)
			if err != nil {
				return "", err
			}
			if f.Anonymous && name == "" {
				embedded = append(embedded, v)
				continue
			}
			if name == "" {
				name = f.Name
			}
			optional := ""
			if slices.Contains(tag[1:], "omitempty") || slices.Contains(tag[1:], "omitzero") {
				optional = "?"
			}
			names = append(names, strconv.Quote(name))
			fields = append(fields, "  "+strconv.Quote(name)+optional+": "+v+";")
		}
		value := "{\n" + strings.Join(fields, "\n") + "\n}"
		if len(embedded) > 0 {
			if len(names) > 0 {
				for i := range embedded {
					embedded[i] = "Omit<" + embedded[i] + ", " + strings.Join(names, " | ") + ">"
				}
			}
			value += " & " + strings.Join(embedded, " & ")
		}
		return value, nil
	default:
		return "", fmt.Errorf("unsupported wire type %s", t)
	}
}
