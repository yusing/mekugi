// Source: openai/codex codex-rs/protocol/src/protocol.rs.
// Inter-agent message shapes visible at the Responses boundary.

const maxActivityEventsPerThread = 64

// Start metadata and any readable assignment come from the child's actual
// request. Native roles can override the parent's model and reasoning settings,
// while opaque native collaboration arguments must remain opaque.
func nativeSubagentStart(request *codexresponses.Request) *binding.SubagentSettings {
	model := request.Model()
	var reasoning struct {
		Effort string `json:"effort"`
	}
	if raw, ok := request.Fields["reasoning"]; ok && json.Unmarshal(raw, &reasoning) != nil {
		return nil
	}
	return binding.SubagentStart(model, reasoning.Effort, responses.StringField(request.Fields, "service_tier"))
}

type subagentInputEnvelopes struct {
	replies []subagentReply
}

type subagentReply struct {
	source  string
	message activitypresentation.SupplementMessage
}

func prepareSubagentInputEnvelopes(fields map[string]json.RawMessage, recipient string) (envelopes subagentInputEnvelopes) {
	var items []map[string]json.RawMessage
	if json.Unmarshal(fields["input"], &items) != nil {
		return envelopes
	}
	currentInput := 0
	for i, item := range items {
		// A later user message or assistant output makes preceding envelopes
		// historical, even if they were never displayed. This boundary
		// also works on full-history requests after resume or cache rebasing.
		kind, role := responses.StringField(item, "type"), responses.StringField(item, "role")
		if (kind == "message" || kind == "") && (role == "user" || role == "assistant") ||
			kind == "reasoning" || strings.HasSuffix(kind, "_call") {
			currentInput = i + 1
		}

	}
	// Replay cleanup is owned by durable provenance reconciliation. Prefixes
	// alone do not prove that a message was generated by this router.
	// An absent or malformed identity cannot establish that an envelope is
	// addressed to this request.
	if recipient != "/root" && !strings.HasPrefix(recipient, "/root/") || strings.ContainsAny(recipient, "\r\n\x00") {
		return envelopes
	}

	for _, item := range items[currentInput:] {
		text, sender, final, ok := binding.SubagentResponse(item)
		if !ok || responses.StringField(item, "recipient") != recipient {
			continue
		}
		if final {
			continue
		}
		id := binding.SubagentMessageID("response\x00" + responses.StringField(item, "id") + "\x00" + sender + "\x00" + text)
		if len(envelopes.replies) < maxActivityEventsPerThread {
			envelopes.replies = append(envelopes.replies, subagentReply{source: id, message: activitypresentation.SupplementMessage{From: sender, To: recipient, Text: text}})
		}
	}
	return envelopes
}

func isFinalAnswerMessage(item map[string]json.RawMessage) bool {
	return responses.Facts(item).FinalAnswerCandidate()
}

// Source: codex-rs/protocol/src/models.rs ContentItem and MessagePhase.
// Codex drops messages with unsupported content (notably refusal parts).
// JSON and SSE must not make usage the only consumable assistant item.
func isSubstantiveAnswer(item map[string]json.RawMessage) bool {
	if !isFinalAnswerMessage(item) {
		return false
	}
	if status := responses.StringField(item, "status"); status != "" && status != "completed" {
		return false
	}
	if raw, present := item["phase"]; present {
		var phase *string
		if json.Unmarshal(raw, &phase) != nil || phase != nil && *phase != "final_answer" {
			return false
		}
	}
	var content []struct {
		Type string  `json:"type"`
		Text *string `json:"text"`
	}
	if json.Unmarshal(item["content"], &content) != nil {
		return false
	}
	substantive := false
	for _, part := range content {
		if part.Type != "output_text" || part.Text == nil {
			return false
		}
		substantive = substantive || strings.TrimSpace(*part.Text) != ""
	}
	return substantive

}

// Client dispatches and unfinished hosted calls are not final-answer turns.
func blocksTokenUsage(item map[string]json.RawMessage) bool {
	switch responses.StringField(item, "type") {
	case "function_call", "custom_tool_call", "computer_call", "local_shell_call", "apply_patch_call", "mcp_approval_request":
		return true
	case "tool_search_call":
		if responses.StringField(item, "execution") != "server" {
			return true
		}
	case "shell_call":
		var environment map[string]json.RawMessage
		if json.Unmarshal(item["environment"], &environment) != nil || responses.StringField(environment, "type") != "container_reference" {
			return true
		}
	}
	if strings.HasSuffix(responses.StringField(item, "type"), "_call") {
		status := responses.StringField(item, "status")
		return status != "completed" && status != "failed"
	}
	return false
}
