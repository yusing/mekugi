func TestToolRegistryExposesOnlyExecutableFrontends(t *testing.T) {
	registry := sharedTestRegistry(t)
	want := []string{"inspect_file", "mcat", "mchanges", "mread", "mrun", "msymbol"}
	var got []string
	entries, err := os.ReadDir(registry.FrontendDirectory)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		name := entry.Name()
		got = append(got, name)
	}
	slices.Sort(got)
	if !slices.Equal(got, want) {
		t.Fatalf("frontends = %v, want %v", got, want)
	}
}

func TestNativeFrontendAuthenticatesCatalogWithoutExternalRuntime(t *testing.T) {
	t.Setenv("PATH", t.TempDir())
	registry, err := buildRegistryForTest(t, t.Context())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := registry.Close(); err != nil {
			t.Error(err)
		}
	})
	source := filepath.Join(t.TempDir(), "source.txt")
	if err := os.WriteFile(source, []byte("native contents\n"), 0600); err != nil {
		t.Fatal(err)
	}
	run := func() (string, string, error) {
		command := exec.CommandContext(t.Context(), filepath.Join(registry.FrontendDirectory, "mcat"), source)
		command.Env = append(os.Environ(), testWorkerEnvironment+"=1", "CODEX_THREAD_ID=")
		var stdout, stderr bytes.Buffer
		command.Stdout, command.Stderr = &stdout, &stderr
		err := command.Run()
		return stdout.String(), stderr.String(), err
	}
	if stdout, stderr, err := run(); err != nil || stdout != "native contents\n" || stderr != "" {
		t.Fatalf("native frontend: stdout %q stderr %q error %v", stdout, stderr, err)
	}
	if err := os.WriteFile(source, []byte("# Generated by fixture\nnative contents\n"), 0600); err != nil {
		t.Fatal(err)
	}
	want, err := (read.Service{}).Execute(t.Context(), command.Request{Args: []string{source}})
	if err != nil || want.Stderr == "" || want.ExitCode != 0 {
		t.Fatalf("generated fixture: %+v, %v", want, err)
	}
	if stdout, stderr, err := run(); err != nil || stdout != want.Stdout || stderr != want.Stderr {
		t.Fatalf("generated frontend: stdout %q stderr %q error %v", stdout, stderr, err)
	}
	manifest, err := readToolWorkerManifest(filepath.Join(registry.SnapshotDir, manifestFilename))
	if err != nil {
		t.Fatal(err)
	}
	manifest.GuidanceSHA256 = "altered"
	if err := writeToolWorkerManifest(registry.SnapshotDir, manifest); err != nil {
		t.Fatal(err)
	}
	if stdout, stderr, err := run(); err == nil || stdout != "" || !strings.Contains(stderr, "registry identity mismatch") {
		t.Fatalf("altered catalog: stdout %q stderr %q error %v", stdout, stderr, err)
	}
}

func TestPreloadMcatRecoveryInAdmittedThread(t *testing.T) {
	registry := sharedTestRegistry(t)
	thread := uniqueTestThread("preload")
	t.Setenv("CODEX_THREAD_ID", thread)
	t.Setenv(testWorkerEnvironment, "1")
	t.Setenv("PATH", registry.FrontendDirectory+string(os.PathListSeparator)+os.Getenv("PATH"))
	path := filepath.Join(t.TempDir(), "selected file.txt")
	body := strings.Repeat("A selected source row that exceeds the ordinary output budget.\n", 5000) + "LAST_SELECTED_ROW\n"
	if err := os.WriteFile(path, []byte(body), 0600); err != nil {
		t.Fatal(err)
	}
	selection, err := json.Marshal(map[string]any{"sources": []string{"@" + path}})
	if err != nil {
		t.Fatal(err)
	}
	// The outer mreload worker retains its session lease while its mcat child runs.
	_, release, err := beginSession(t.Context(), testHistory(), registry.ReplayDirectory, thread)
	if err != nil {
		t.Fatal(err)
	}
	defer release()
	captured, err := (compact.Readers{}).Capture(t.Context(), command.Request{Args: []string{string(selection)}})
	if err != nil {
		t.Fatal(err)
	}
	prepared, err := captured.Delivery.Prepare([]string{"snapshot"})
	if err != nil {
		t.Fatal(err)
	}
	var snapshot compact.Snapshot
	if err := json.Unmarshal([]byte(prepared.Recovery[0].Stdout), &snapshot); err != nil {
		t.Fatal(err)
	}
	// Claude invokes ReadSources directly with the child environment.
	claude, err := compact.ReadSources(t.Context(), string(selection), "", os.Environ(), compact.ChangeReader{})
	if err != nil {
		t.Fatal(err)
	}
	for _, source := range []compact.CapturedSource{snapshot.Sources[0], claude.Sources[0]} {
		if source.ExitCode == 0 || !strings.HasPrefix(source.Command, "'mcat'") {
			t.Fatalf("expected an incomplete mcat source: %+v", source)
		}
		output := source.Stdout + source.Stderr
		for page := 0; page < 30 && !strings.Contains(output, "LAST_SELECTED_ROW"); page++ {
			_, rest, ok := strings.Cut(output, "next_call: mread ")
			if !ok {
				t.Fatalf("missing recovery for incomplete preload: %s", output)
			}
			line, _, _ := strings.Cut(rest, "\n")
			cmd := exec.CommandContext(t.Context(), filepath.Join(registry.FrontendDirectory, "mread"), strings.Fields(line)...)
			pageOutput, err := cmd.CombinedOutput()
			if err != nil && len(pageOutput) == 0 {
				t.Fatalf("mread failed: %v", err)
			}
			output = string(pageOutput)
		}
		if !strings.Contains(output, "LAST_SELECTED_ROW") {
			t.Fatal("recovery did not reach the selected source end")
		}
	}
}
